// Tiny local web server for testing. Not for production.
// Usage: node scripts/serve.mjs <folder> [port] [basePath]
//   basePath lets us test the GitHub Pages sub-path, e.g. /cf_website_v2/
import { createReadStream, statSync } from "node:fs";
import { createServer } from "node:http";
import { extname, join, normalize, resolve, sep } from "node:path";
import { pathToFileURL } from "node:url";
import { existsSync, readFileSync } from "node:fs"; // for reading _headers
import { loadConfig, qrSvg, renderHtml } from "./render.mjs";

export function serve(folder = ".", port = 8000, basePath = "/") {
  const root = resolve(folder);
  const base = ("/" + basePath + "/").replace(/\/+/g, "/");
  const types = {
    ".html": "text/html; charset=utf-8", ".css": "text/css; charset=utf-8", ".js": "text/javascript; charset=utf-8",
    ".json": "application/json", ".svg": "image/svg+xml", ".png": "image/png", ".jpg": "image/jpeg", ".jpeg": "image/jpeg",
    ".webp": "image/webp", ".ico": "image/x-icon", ".woff2": "font/woff2", ".txt": "text/plain; charset=utf-8", ".xml": "application/xml",
  };
  // Tooling folders and config files are never served. Hidden files (.env, .git...) are blocked below.
  const blocked = ["node_modules", "scripts", "src", "package.json", "package-lock.json", "tailwind.config.js", "vercel.json", "site.config.json", "stories.json"];
  // In dev mode (serving the source folder) pages get the same values the build fills in
  const hasConfig = () => existsSync(join(root, "site.config.json"));

  // Send the same security headers as the real hosting (from _headers), so problems show up locally.
  // Read on every request, so edits to _headers apply without a restart.
  function securityHeaders() {
    const file = join(root, "_headers");
    if (!existsSync(file)) return {};
    const headers = {};
    let inBlock = false;
    for (const line of readFileSync(file, "utf8").split(/\r?\n/)) {
      if (/^\S/.test(line)) inBlock = line.trim() === "/*";
      else if (inBlock && line.includes(":")) {
        const i = line.indexOf(":");
        headers[line.slice(0, i).trim()] = line.slice(i + 1).trim();
      }
    }
    delete headers["Strict-Transport-Security"]; // only meaningful over HTTPS
    return headers;
  }

  createServer(async (req, res) => {
    let path;
    try { path = decodeURIComponent(new URL(req.url, "http://localhost").pathname); }
    catch { res.writeHead(400).end("Bad request"); return; }

    if (base !== "/" && path === base.slice(0, -1)) { res.writeHead(301, { Location: base }).end(); return; }
    if (!path.startsWith(base)) { res.writeHead(404).end("Not found"); return; }

    let file = normalize(join(root, path.slice(base.length)));
    // Never serve anything outside the folder, or tooling folders
    const rel = file.slice(root.length + 1).split(sep);
    const hidden = rel.some((part) => part.startsWith(".") && part !== ".well-known");
    if ((file !== root && !file.startsWith(root + sep)) || blocked.includes(rel[0]) || hidden) { res.writeHead(404).end("Not found"); return; }

    // Dev mode: the poster's QR code is generated by the build, so make it on the fly here
    if (rel.join("/") === "images/qr.svg" && !existsSync(file) && hasConfig()) {
      res.writeHead(200, { ...securityHeaders(), "Content-Type": types[".svg"], "Cache-Control": "no-store" });
      res.end(await qrSvg(loadConfig(root).siteUrl));
      return;
    }

    try { if (statSync(file).isDirectory()) file = join(file, "index.html"); statSync(file); }
    catch { res.writeHead(404, { "Content-Type": "text/plain" }).end("Not found"); return; }

    const type = types[extname(file).toLowerCase()] || "application/octet-stream";
    res.writeHead(200, { ...securityHeaders(), "Content-Type": type, "Cache-Control": "no-store" });
    if (extname(file) === ".html" && hasConfig()) { res.end(renderHtml(readFileSync(file, "utf8"), loadConfig(root))); return; }
    createReadStream(file).pipe(res);
  }).listen(port, "127.0.0.1", () => {
    console.log(`Serving ${folder} at http://localhost:${port}${base}`);
  });
}

// Run directly from the command line
if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const [, , folder = ".", port = "8000", basePath = "/"] = process.argv;
  serve(folder, Number(port), basePath);
}
